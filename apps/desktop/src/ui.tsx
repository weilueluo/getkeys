/** Lets dialogs show the app's error, since everything behind an open dialog is inert. */
export const DialogHost = createContext<{ error: string; opened: (delta: number) => void }>({
  error: '',
  opened: () => {},
});

export function Modal({
  title,
  children,
  onClose,
  description,
  wide = false,
}: {
  title: string;
  children: ReactNode;
  onClose: () => void;
  description?: ReactNode;
  wide?: boolean;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  const titleId = useId();
  const { error, opened } = useContext(DialogHost);
  useEffect(() => {
    const dialog = ref.current!;
    dialog.showModal();
    opened(1);
    return () => {
      dialog.close();
      opened(-1);
    };
  }, [opened]);
  return (
    <dialog
      ref={ref}
      className={wide ? 'modal wide' : 'modal'}
      aria-labelledby={titleId}
      onCancel={(e) => {
        e.preventDefault();
        onClose();
      }}
    >
      <div className="modal-heading">
        <div>
          <h2 id={titleId}>{title}</h2>
          {description && <p className="modal-description">{description}</p>}
        </div>
        <button type="button" className="icon-button" aria-label="Close dialog" onClick={onClose}>
          <X size={16} />
        </button>
      </div>
      {error && (
        <div role="alert" className="alert">
          <TriangleAlert size={16} strokeWidth={1.75} />
          <span>{error}</span>
        </div>
      )}
      {children}
    </dialog>
  );
}

export function Tabs<T extends string>({
  label,
  value,
  onChange,
  tabs,
}: {
  label: string;
  value: T;
  onChange: (value: T) => void;
  tabs: { id: T; label: string; count?: number }[];
}) {
  return (
    <div className="tabs" role="tablist" aria-label={label}>
      {tabs.map((t) => (
        <button
          key={t.id}
          type="button"
          role="tab"
          aria-selected={value === t.id}
          className="tab"
          onClick={() => onChange(t.id)}
        >
          {t.label}
          {t.count !== undefined && <span className="count">{t.count}</span>}
        </button>
      ))}
    </div>
  );
}

/** A button that opens a small list of choices beside it. */
export function Menu({
  label,
  button,
  className = 'icon-button outline',
  title,
  align = 'start',
  children,
}: {
  label: string;
  button: ReactNode;
  className?: string;
  title?: string;
  align?: 'start' | 'end';
  children: (close: () => void) => ReactNode;
}) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const outside = (e: PointerEvent) => {
      if (!ref.current?.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener('pointerdown', outside);
    return () => document.removeEventListener('pointerdown', outside);
  }, [open]);
  return (
    <div
      className="menu-anchor"
      ref={ref}
      onKeyDown={(e) => {
        if (e.key === 'Escape' && open) {
          e.stopPropagation();
          e.preventDefault();
          setOpen(false);
        }
      }}
    >
      <button
        type="button"
        className={className}
        aria-label={label}
        title={title ?? label}
        aria-haspopup="menu"
        aria-expanded={open}
        onClick={() => setOpen(!open)}
      >
        {button}
      </button>
      {open && (
        <div className={`menu ${align}`} role="menu" aria-label={label}>
          {children(() => setOpen(false))}
        </div>
      )}
    </div>
  );
}

